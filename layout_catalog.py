def get_template(layout_id: str) -> Optional[Template]:
    """Accepts a template id (L07), a name ('Data Grid Table') or a label ('L07 · ...')."""
    if not layout_id:
        return None
    key = str(layout_id).strip()
    if key in BY_ID:
        return BY_ID[key]
    if key in ID_BY_NAME:
        return BY_ID[ID_BY_NAME[key]]
    if key in BY_NAME:
        return BY_NAME[key]
    if key in ID_BY_LABEL:
        return BY_ID[ID_BY_LABEL[key]]
    # tolerate "L07 Data Grid Table" / "07"
    token = key.split()[0] if key.split() else ""
    if token.isdigit() and len(token) == 2:
        return BY_ID.get("L" + token)
    return None


def template_label(layout_id: str) -> str:
    t = get_template(layout_id)
    return t.label if t else str(layout_id or "")


def kind_spec(kind: str) -> Dict[str, Any]:
    return KINDS.get(kind, KINDS["bullets"])


def sample_content(kind: str) -> Dict[str, Any]:
    import copy
    return copy.deepcopy(kind_spec(kind)["sample"])


def catalogue_for_llm() -> List[Dict[str, Any]]:
    """Compact, token-friendly index of every layout for the LLM planner."""
    out = []
    for t in TEMPLATES:
        out.append({
            "id": t.id,
            "name": t.name,
            "family": t.family,
            "best_for": t.best_for,
            "content_pattern": t.content_pattern,
            "density": t.density,
        })
    return out


def catalogue_markdown() -> str:
    """Human readable catalogue (also used to write the reference markdown file)."""
    lines = [
        "# Presentation Layout Template Catalogue",
        "",
        f"**Total templates: {len(TEMPLATES)}** "
        f"({len(ORIGINAL_LAYOUTS)} from the original archetype library, "
        f"{len(ADDED_LAYOUTS)} added to close the gaps in it).",
        "",
        "| ID | Template | Family | Use it when | Content pattern |",
        "| --- | --- | --- | --- | --- |",
    ]
    for t in TEMPLATES:
        lines.append(
            f"| `{t.id}` | **{t.name}** | {t.family} | {t.best_for} | {t.content_pattern} |"
        )
    lines += ["", "## Additions and why they were added", ""]
    for t in ADDED_LAYOUTS:
        lines.append(f"- **`{t.id}` {t.name}** - {t.added}")
    lines.append("")
    return "\n".join(lines)
