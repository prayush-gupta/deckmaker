"""layout_catalog.py - Master catalogue of slide layout templates (archetypes).

The catalogue is the single source of truth for:
  * which layouts exist (id, name, family, when to use it),
  * the structured content shape each layout needs (the "kind"),
  * sample content used to draw the template specimen (preview + sample deck).

The original 44 archetypes from `presentation_layout_library.py` are kept with their
stable IDs (L01..L44).  L45..L68 are additions that fill the gaps in the original
list (see `ADDED_LAYOUTS` for the rationale of every addition).

A layout is NEVER described by coordinates.  It is described by:
    id + name + family + best_for + content_pattern + a content "kind".
The renderer (slide_layout_engine.py) knows how to draw each kind, and the LLM planner
returns `id` + structured content.  That keeps layout selection, content
generation and rendering separate, exactly as the library notes recommend.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

# --------------------------------------------------------------------------------------
# Template record
# --------------------------------------------------------------------------------------


@dataclass(frozen=True)
class Template:
    id: str
    name: str
    family: str
    kind: str
    best_for: str
    content_pattern: str
    implementation: str
    density: str = "medium"
    image_strategy: str = "Optional; use only when it adds evidence or context."
    added: str = ""          # non-empty -> added on top of the original 44

    # -- convenience -------------------------------------------------------------
    @property
    def label(self) -> str:
        return f"{self.id} · {self.name}"

    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "name": self.name,
            "family": self.family,
            "best_for": self.best_for,
            "content_pattern": self.content_pattern,
            "implementation": self.implementation,
            "density": self.density,
            "image_strategy": self.image_strategy,
        }


# --------------------------------------------------------------------------------------
# Content kinds - the structured shape the LLM must produce for each layout
# --------------------------------------------------------------------------------------
# fields      : {field_name: human readable description of the value}
# required    : fields that must be present
# item_key    : which field holds the repeating element (None = no repeating element)
# min/max     : allowed number of repeating elements
# sample      : representative content, used for the template specimen render


def _k(fields, required, sample, item_key=None, min_items=None, max_items=None):
    return {
        "fields": fields,
        "required": list(required),
        "sample": sample,
        "item_key": item_key,
        "min_items": min_items,
        "max_items": max_items,
    }


